ALTER TABLE interventions ADD COLUMN follow_up_status VARCHAR(20) DEFAULT 'NONE' NOT NULL;
UPDATE interventions SET follow_up_status = CASE
  WHEN next_date IS NULL THEN 'NONE'
  ELSE 'PLANNED'
END;
UPDATE interventions i SET follow_up_status = 'SUPERSEDED'
  WHERE i.follow_up_status = 'PLANNED' AND EXISTS (
    SELECT 1 FROM interventions newer
    WHERE newer.alert_id = i.alert_id AND
      (newer.created_at > i.created_at OR
        (newer.created_at = i.created_at AND newer.id > i.id))
  );
UPDATE interventions i SET follow_up_status = 'CANCELLED'
  WHERE i.follow_up_status = 'PLANNED' AND EXISTS (
    SELECT 1 FROM alerts a WHERE a.id = i.alert_id AND a.status = 'CLOSED'
  );
ALTER TABLE interventions ADD CONSTRAINT ck_interventions_follow_up_status
  CHECK (follow_up_status IN ('NONE', 'PLANNED', 'SUPERSEDED', 'CANCELLED'));
CREATE INDEX idx_interventions_follow_up
  ON interventions(alert_id, follow_up_status, next_date);
